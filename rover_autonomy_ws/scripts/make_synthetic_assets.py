"""Generate clearly labeled synthetic sign fixtures, not camera training data."""

import json
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def sign_image(label: str, white_arrow: bool = False):
    if label in ("green_light", "red_light"):
        image = np.full((160, 100, 3), 230, np.uint8)
        cv2.rectangle(image, (12, 5), (88, 154), (22, 22, 22), -1)
        for index, center in enumerate(((50, 32), (50, 80), (50, 127))):
            color = (
                (0, 0, 235)
                if label == "red_light" and index == 0
                else (0, 215, 0)
                if label == "green_light" and index == 2
                else (35, 35, 35)
            )
            cv2.circle(image, center, 18, color, -1)
        return image
    image = np.full((160, 160, 3), 230, np.uint8)
    cv2.circle(image, (80, 80), 74, (225, 80, 10), -1)
    cv2.circle(image, (80, 80), 72, (245, 245, 245), 3)
    points = np.array([(30, 65), (80, 65), (80, 40), (126, 80), (80, 120), (80, 95), (30, 95)], np.int32)
    if label == "left":
        points[:, 0] = 160 - points[:, 0]
    color = (245, 245, 245) if white_arrow else (20, 20, 20)
    cv2.fillPoly(image, [points], color)
    if not white_arrow:
        cv2.polylines(image, [points], True, (245, 245, 245), 2)
    return image


def main():
    destination = ROOT / "tests/assets"
    destination.mkdir(parents=True, exist_ok=True)
    for label in ("green_light", "red_light", "left", "right"):
        ok, encoded = cv2.imencode(".png", sign_image(label))
        if not ok:
            raise RuntimeError("Synthetic fixture encoding failed")
        (destination / f"sign_{label}.png").write_bytes(encoded.tobytes())
    (destination / "sign_sources.json").write_text(
        json.dumps(
            {
                "source": "Generated by scripts/make_synthetic_assets.py",
                "kind": "synthetic graphics only",
                "real_camera_photos": False,
                "accuracy_claim": "none",
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print("Generated four synthetic fixtures; no camera photographs or labels were used.")


if __name__ == "__main__":
    main()
